import { readFileSync, writeFileSync } from 'node:fs'
const root = new URL('../', import.meta.url)
const read = name => readFileSync(new URL(name, root), 'utf8').replace(/\r\n/g, '\n')
const stripExports = source => source.replace(/^export /gm, '')
const requestSource = stripExports(read('src/lib/auth-request.js'))
const helper = read('src/lib/auth-session.js').replace(/^export /gm, '')
const indent = source => source.split('\n').map(line => line ? `    ${line}` : '').join('\n')
const output = read('src/client.entry.js')
  .replace('    /* @AUTH_REQUEST@ */', indent(requestSource))
  .replace('    /* @AUTH_SESSION@ */', indent(helper))
const bootstrapScript = `(()=>{const key='__HANACCOUNT_BOOTSTRAP_V1__';if(Object.prototype.hasOwnProperty.call(window,key))return;try{${requestSource}\n${helper}\nconst session=createAuthSession({request:createAuthRequest({fetchImpl:(...args)=>fetch(...args),base:'/dsh-local-hanaccount/api',origin:location.origin}),timeoutMs:5000});let claimed=false,live=true;const retire=()=>{if(!claimed&&live){live=false;session.dispose()}};const holder=Object.freeze({protocol:1,claim(){if(claimed||!live)return null;claimed=true;return session},dispose:retire});Object.defineProperty(window,key,{value:holder,configurable:true});window.addEventListener('pagehide',retire,{once:true});session.refresh()}catch{}})();`
const bootstrapModule = `// Generated by scripts/bundle.mjs from auth-request.js and auth-session.js.\nexport const AUTH_BOOTSTRAP_SCRIPT = ${JSON.stringify(bootstrapScript)}\n`
const bootstrapPath = new URL('src/lib/auth-bootstrap.generated.js', root)
if (process.argv.includes('--check')) {
  if (read('src/client.js') !== output) throw new Error('client.js is stale; run npm run build')
  if (read('src/lib/auth-bootstrap.generated.js') !== bootstrapModule) throw new Error('auth bootstrap is stale; run npm run build')
} else {
  writeFileSync(new URL('src/client.js', root), output)
  writeFileSync(bootstrapPath, bootstrapModule)
}
